"""Skill package filesystem layer: safe extraction, classification and deterministic compilation.

The package on disk is the source of truth; database rows only describe it.  Nothing
here executes package content and nothing here is generated by a model.
"""
from __future__ import annotations

import hashlib
import io
import json
import re
import shutil
from pathlib import Path, PurePosixPath
from zipfile import BadZipFile, ZipFile

MAX_PACKAGE_BYTES = 20 * 1024 * 1024
MAX_FILES = 1000
MAX_FILE_BYTES = 5 * 1024 * 1024
MAX_TEXT_BYTES = 2 * 1024 * 1024
MAX_READ_CHARS = 20000

TEXT_SUFFIXES = {'.md', '.markdown', '.txt', '.json', '.yaml', '.yml', '.csv'}
SCRIPT_SUFFIXES = {'.py', '.ps1', '.sh', '.bat', '.cmd', '.js', '.mjs', '.rb'}
IMAGE_SUFFIXES = {'.png', '.jpg', '.jpeg', '.webp', '.svg', '.gif', '.ico', '.bmp'}
SKIP_DIRS = {'__pycache__', '.git', '.svn', 'node_modules'}

CORE_FILES = (
    'SKILL.md',
    'references/prompt-writing-standard.md',
    'references/prompt-composition.md',
    'references/quality-gate.md',
)
COMPILE_EXCLUDED = {'references/generation-profile.md', 'references/sources.md'}
COMPILE_LEVELS = ('core', 'full')


class ImportRejected(ValueError):
    """A package that violates a documented import rule."""


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def normalize_member(name: str) -> str:
    """Return a safe POSIX relative path or raise ImportRejected."""
    value = name.replace('\\', '/').strip().lstrip('/')
    if not value:
        raise ImportRejected('压缩包内存在空文件名。')
    if re.match(r'^[A-Za-z]:', value):
        raise ImportRejected('压缩包内不能包含绝对路径。')
    parts = [part for part in value.split('/') if part not in ('', '.')]
    if not parts:
        raise ImportRejected('压缩包内存在无效路径。')
    if any(part == '..' for part in parts):
        raise ImportRejected('压缩包内不能包含 ../ 路径。')
    return '/'.join(parts)


def _zip_name(info) -> str:
    raw = info.filename
    if info.flag_bits & 0x800:
        return raw
    try:
        value = raw.encode('cp437')
    except UnicodeEncodeError:
        return raw
    for encoding in ('utf-8', 'gbk'):
        try:
            return value.decode(encoding)
        except UnicodeDecodeError:
            continue
    return raw


def safe_join(root: Path, relative: str) -> Path:
    target = (root / PurePosixPath(relative)).resolve()
    base = root.resolve()
    if target != base and not target.is_relative_to(base):
        raise ImportRejected('文件路径超出了技能目录。')
    return target


def extract_archive(data: bytes, destination: Path) -> list[dict]:
    """Extract a zip into destination with size, count and path-traversal limits."""
    if not data:
        raise ImportRejected('请选择要导入的压缩包。')
    if len(data) > MAX_PACKAGE_BYTES:
        raise ImportRejected('压缩包不能超过 20 MB。')
    destination.mkdir(parents=True, exist_ok=True)
    total, written = 0, []
    try:
        with ZipFile(io.BytesIO(data)) as archive:
            for info in archive.infolist():
                if info.is_dir():
                    continue
                if (info.external_attr >> 16) & 0o170000 == 0o120000:
                    raise ImportRejected('压缩包内不能包含符号链接。')
                relative = normalize_member(_zip_name(info))
                if info.file_size > MAX_FILE_BYTES:
                    raise ImportRejected(f'文件超过 5 MB：{relative}')
                total += info.file_size
                if total > MAX_PACKAGE_BYTES:
                    raise ImportRejected('解压后的总大小超过 20 MB。')
                if len(written) >= MAX_FILES:
                    raise ImportRejected('文件数超过 1000。')
                target = safe_join(destination, relative)
                target.parent.mkdir(parents=True, exist_ok=True)
                with archive.open(info) as source, target.open('wb') as handle:
                    shutil.copyfileobj(source, handle, 1024 * 1024)
                written.append({'path': relative, 'size': target.stat().st_size})
    except BadZipFile:
        raise ImportRejected('文件不是有效的 zip 压缩包。') from None
    if not written:
        raise ImportRejected('压缩包是空的。')
    return written


def write_uploads(destination: Path, pairs: list[tuple[str, bytes]]) -> list[dict]:
    """Folder-selection import: pairs of (relative path, content)."""
    if not pairs:
        raise ImportRejected('请选择要导入的文件夹。')
    if len(pairs) > MAX_FILES:
        raise ImportRejected('文件数超过 1000。')
    destination.mkdir(parents=True, exist_ok=True)
    total, written = 0, []
    for relative_raw, content in pairs:
        relative = normalize_member(relative_raw)
        if len(content) > MAX_FILE_BYTES:
            raise ImportRejected(f'文件超过 5 MB：{relative}')
        total += len(content)
        if total > MAX_PACKAGE_BYTES:
            raise ImportRejected('导入文件总大小超过 20 MB。')
        target = safe_join(destination, relative)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        written.append({'path': relative, 'size': len(content)})
    return written


def walk_files(root: Path) -> list[str]:
    values = []
    for path in root.rglob('*'):
        if not path.is_file():
            continue
        relative = path.relative_to(root).as_posix()
        if any(part in SKIP_DIRS for part in PurePosixPath(relative).parts):
            continue
        if path.name in ('.DS_Store', 'Thumbs.db'):
            continue
        values.append(relative)
    return sorted(values)


def kind_for(relative: str) -> str:
    parts = PurePosixPath(relative).parts
    name = parts[-1].lower()
    suffix = PurePosixPath(name).suffix
    if name == 'skill.md' and len(parts) == 1:
        return 'entry'
    if name.startswith('license') or 'licenses' in parts:
        return 'license'
    if relative in COMPILE_EXCLUDED or parts[0] == 'runtime':
        return 'execution'
    if suffix in SCRIPT_SUFFIXES:
        return 'script'
    if suffix in IMAGE_SUFFIXES:
        return 'asset'
    if suffix in {'.json', '.yaml', '.yml'}:
        return 'template'
    if suffix in {'.md', '.markdown', '.txt', '.csv'}:
        return 'reference'
    return 'other'


def is_text(relative: str) -> bool:
    return PurePosixPath(relative).suffix.lower() in TEXT_SUFFIXES


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
        return value[1:-1]
    return value


def parse_frontmatter(text: str) -> dict:
    lines = text.splitlines()
    if not lines or lines[0].strip() != '---':
        return {}
    end = next((index for index in range(1, len(lines)) if lines[index].strip() == '---'), None)
    if end is None:
        return {}
    root: dict = {}
    stack: list[tuple[int, dict]] = [(0, root)]
    for raw in lines[1:end]:
        if not raw.strip() or raw.lstrip().startswith('#'):
            continue
        indent = len(raw) - len(raw.lstrip())
        key, separator, value = raw.strip().partition(':')
        if not separator or not key:
            continue
        while len(stack) > 1 and indent < stack[-1][0]:
            stack.pop()
        container = stack[-1][1]
        value = value.strip()
        if value:
            container[key.strip()] = _unquote(value)
        else:
            child: dict = {}
            container[key.strip()] = child
            stack.append((indent + 2, child))
    return root


def _read_capped(path: Path) -> str:
    with path.open('rb') as handle:
        raw = handle.read(MAX_TEXT_BYTES + 1)
    return raw[:MAX_TEXT_BYTES].decode('utf-8', errors='replace')


def find_skill_roots(package_root: Path) -> list[dict]:
    """Every directory containing a top-level SKILL.md is one skill."""
    found = []
    for relative in walk_files(package_root):
        if PurePosixPath(relative).name.lower() != 'skill.md':
            continue
        directory = PurePosixPath(relative).parent
        if str(directory) == '.':
            skill_root, label = package_root, '.'
        else:
            skill_root, label = package_root / Path(directory), str(directory)
        text = _read_capped(skill_root / 'SKILL.md')
        meta = parse_frontmatter(text)
        metadata = meta.get('metadata') if isinstance(meta.get('metadata'), dict) else {}
        name = str(meta.get('name') or skill_root.name).strip()[:200]
        description = str(meta.get('description') or '').strip()
        version = str(metadata.get('version') or meta.get('version') or '').strip() or '0.0.0'
        found.append({'root': label, 'path': skill_root, 'name': name,
                      'description': description, 'version_label': version[:64],
                      'entry_text': text})
    found.sort(key=lambda item: item['root'])
    return found


def file_entries(skill_root: Path) -> list[dict]:
    values = []
    for relative in walk_files(skill_root):
        path = skill_root / relative
        values.append({'path': relative, 'kind': kind_for(relative), 'size': path.stat().st_size,
                       'sha256': sha256_file(path), 'is_text': is_text(relative)})
    return values


def content_fingerprint(files: list[dict]) -> str:
    digest = hashlib.sha256()
    for item in sorted(files, key=lambda value: value['path']):
        digest.update(item['path'].encode('utf-8'))
        digest.update(b'\0')
        digest.update(item['sha256'].encode('ascii'))
        digest.update(b'\n')
    return digest.hexdigest()


def _compile_paths(files: list[dict], level: str) -> list[str]:
    available = {item['path'] for item in files if item['is_text']}
    if level == 'full':
        ordered = [path for path in available if path == 'SKILL.md']
        ordered += sorted(path for path in available
                          if path.startswith('references/') and path not in COMPILE_EXCLUDED)
        return ordered
    return [path for path in CORE_FILES if path in available]


def compile_context(skill_root: Path, files: list[dict], level: str = 'core') -> tuple[str, list[dict]]:
    """Deterministic concatenation.  No model is involved and nothing is summarised."""
    if level not in COMPILE_LEVELS:
        raise ImportRejected('未知的预编译档位。')
    chunks, index, cursor = [], [], 0
    for relative in _compile_paths(files, level):
        content = _read_capped(skill_root / relative)
        block = f'<!-- FILE: {relative} -->\n\n{content}\n\n'
        index.append({'path': relative, 'start': cursor, 'end': cursor + len(block)})
        chunks.append(block)
        cursor += len(block)
    return ''.join(chunks), index


def verify_manifest(package_root: Path) -> dict:
    path = package_root / 'manifest.json'
    if not path.is_file():
        return {'present': False, 'ok': True, 'missing': [], 'mismatch': [], 'checked': 0}
    try:
        data = json.loads(_read_capped(path))
        rows = data.get('files') if isinstance(data, dict) else None
        if not isinstance(rows, list):
            raise ValueError()
    except (ValueError, AttributeError):
        return {'present': True, 'ok': False, 'missing': [], 'mismatch': [],
                'checked': 0, 'message': 'manifest.json 格式无法识别。'}
    missing, mismatch = [], []
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get('path'), str):
            continue
        relative = row['path'].replace('\\', '/').lstrip('/')
        expected = row.get('sha256')
        candidate = package_root / PurePosixPath(relative)
        if not candidate.is_file():
            missing.append(relative)
        elif isinstance(expected, str) and sha256_file(candidate) != expected.lower():
            mismatch.append(relative)
    return {'present': True, 'ok': not missing and not mismatch, 'missing': missing,
            'mismatch': mismatch, 'checked': len(rows)}


def read_text(skill_root: Path, relative: str, offset: int = 0, limit: int = MAX_READ_CHARS) -> dict:
    relative = normalize_member(relative)
    if not is_text(relative):
        raise ImportRejected('该文件不是可读的文本文件。')
    path = safe_join(skill_root, relative)
    if not path.is_file():
        raise ImportRejected('技能文件不存在。')
    text = _read_capped(path)
    offset = max(0, min(offset, len(text)))
    limit = max(1, min(limit, MAX_READ_CHARS))
    chunk = text[offset:offset + limit]
    return {'path': relative, 'offset': offset, 'total_chars': len(text), 'content': chunk,
            'truncated': offset + len(chunk) < len(text)}


def copy_tree(source: Path, destination: Path) -> None:
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(source, destination)
